-- 5. 맵 옮기기: 이어짐 표만 본다
create or replace function public.adventure_move(target text) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  a public.adventure_players%rowtype;
  l public.adventure_links%rowtype;
  here_zone text;
begin
  perform 1 from public.profiles as p where p.id = auth.uid() for update;
  if not found then
    raise exception 'no profile';
  end if;
  a := public.adventure_prepare(auth.uid());
  if not a.in_run then
    raise exception 'no run';
  end if;
  if adventure_move.target is distinct from a.run_map then
    select * into l from public.adventure_links as x where x.from_map = a.run_map and x.to_map = adventure_move.target;
    if not found then
      raise exception 'bad map';
    end if;
    if l.need = 'boss' then
      -- 다음 지역: 이번 판에 지금 맵 지역 보스를 잡았을 때만(별 하늘은 보스 둘 가운데 하나, 지역 키 하나)
      select x.zone into here_zone from public.adventure_maps as x where x.map = a.run_map;
      if here_zone is null or not (here_zone = any (a.run_bosses)) then
        raise exception 'zone locked';
      end if;
    elsif l.need = 'gate' then
      -- 높은 지역 포탈(평원 1 → 화산 폭풍 1): 이번 판에 지금 맵 수문장을 이겼을 때만(2026-11-19 사용자), 한쪽으로만
      if not (('gate:' || a.run_map) = any (a.run_bosses)) then
        raise exception 'zone locked';
      end if;
    end if;
    update public.adventure_players as x set run_map = l.to_map where x.player = auth.uid();
  end if;
  return public.adventure_view(auth.uid());
end;
$$;

revoke execute on function public.adventure_move(text) from public, anon;
grant execute on function public.adventure_move(text) to authenticated;
